'use strict';
/* Standalone module QA. Fabricación callbacks are from the game, never duplicated. */
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {chromium}=require('playwright');
const root=path.resolve(__dirname,'..');
const out=path.join(root,'previews','fabricaciones-module-v001');
fs.mkdirSync(out,{recursive:true});
const art='assets/ui/fabricaciones/module_v001/fabricaciones_estructura_limpia_v001.png';
assert(fs.existsSync(path.join(root,art)),'Clean asset must be generated by Blender/Github Actions build stage');
const src=fs.readFileSync(path.join(root,'modules/fabricaciones_v001.js'),'utf8');
const approved=fs.readFileSync(path.join(root,'genesis_ui_approved.js'),'utf8');
assert.match(approved,/craftingV001=1/,'Source requires an explicit opt-in guard');
assert.match(approved,/if\(!experimentalFabricaciones\(ctx,nav\)\)fabrications\(ctx,nav\)/);
assert(!src.includes('const recipes=[{'),'Module may not hardcode recipes or item stats');
assert(!src.includes('recipeAsset?.('),'Never use ingot as sword model');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
 try {
  const page=await browser.newPage({viewport:{width:1600,height:900},deviceScaleFactor:1});
  const issues=[];page.on('pageerror',e=>issues.push(e.message));
  page.on('requestfailed',req=>issues.push(req.url()+':'+(req.failure()?.errorText||'unknown')));
  await page.route('**/*',async route=>{
    const u=new URL(route.request().url());
    if(u.pathname==='/')return route.fulfill({status:200,contentType:'text/html',body:'<!doctype html><html><head><meta charset="UTF-8"></head><body style="margin:0;background:#080605"><div id="modal"></div></body></html>'});
    const file=path.resolve(root,decodeURIComponent(u.pathname).replace(/^\/+/,'')); 
    if(!file.startsWith(root+path.sep)||!fs.existsSync(file)||!fs.statSync(file).isFile())return route.abort('failed');
    const ext=path.extname(file).toLowerCase(),mime=ext==='.png'?'image/png':ext==='.jpg'?'image/jpeg':ext==='.webp'?'image/webp':ext==='.css'?'text/css':'application/javascript';
    return route.fulfill({status:200,contentType:mime,body:fs.readFileSync(file)});
  });
  await page.goto('http://genesis.local/');
  await page.addStyleTag({content:fs.readFileSync(path.join(root,'genesis_ui_approved.css'),'utf8')});
  await page.addStyleTag({content:fs.readFileSync(path.join(root,'modules/fabricaciones_v001.css'),'utf8')});
  await page.addScriptTag({content:src});
  await page.evaluate(()=>{
    window.__CALLS__=[];
    const recipes=[
     {id:'espada_hierro',family:'Espadas',subfamily:'Espada de hierro',formula:{materials:[
       {material:'Lingote de hierro',qty:2},{material:'Madera seca de roble',qty:1},{material:'Carbón vegetal',qty:1}
     ]}},
     {id:'escudo_hierro',family:'Escudos',subfamily:'Escudo de hierro',formula:{materials:[
       {material:'Lingote de hierro',qty:2},{material:'Madera seca de roble',qty:1},{material:'Cuero bovino curtido',qty:1}
     ]}},
    ];
    const context={profession:'Herrero',activeRecipeId:'espada_hierro',selectedRecipeId:'espada_hierro',inventory:{
       'Lingote de hierro':6,'Madera seca de roble':4,'Carbón vegetal':2,'Cuero bovino curtido':3},
      getRecipeCatalog:()=>recipes,
      canCraftRecipe:id=>true,
      modal(markup){document.body.innerHTML='<div class="modal preparationModal genesisApprovedModal" id="modal">'+markup+'</div>'}
    };
    const nav={renderMenu(){window.__CALLS__.push('preparacion')},
      renderWorkspace(tab){window.__CALLS__.push('tab:'+tab)},
      craft(){window.__CALLS__.push('craft:'+context.selectedRecipeId)},close(){window.__CALLS__.push('close')}};
    window.__CTX__=context;window.__NAV__=nav;
    window.GenesisCraftingModule.render(context,nav);
  });
  await page.locator('.gCraftModule').waitFor();
  await page.locator('.gCraftIngredient').first().waitFor();
  assert.equal(await page.locator('.gCraftRecipe').count(),2);
  assert.equal(await page.locator('.gCraftRecipe.active').count(),1);
  assert.equal(await page.locator('.gCraftViewer img').count(),0,'No generic/static weapon may be baked into live viewport');
  assert.equal(await page.locator('.gCraftViewer model-viewer').count(),0,'No model without certified game source');
  assert.equal(await page.locator('.gCraftIngredient').count(),3);
  assert.equal(await page.locator('.gCraftRecipeDetails h2').innerText(),'Espada de hierro');
  assert.equal(await page.locator('.gCraftMake').isEnabled(),true);
  await page.screenshot({path:path.join(out,'01-espada-recetas-y-materiales-dinamicos-1600x900.png'),animations:'disabled',timeout:30000});
  await page.locator('.gCraftMake').click();
  assert.equal(await page.evaluate(()=>window.__CALLS__.at(-1)),'craft:espada_hierro');
  await page.locator('[data-craft-recipe="escudo_hierro"]').click();
  assert.equal(await page.locator('.gCraftRecipe.active').count(),1,'Only one recipe may be selected');
  assert.equal(await page.locator('.gCraftRecipeDetails h2').innerText(),'Escudo de hierro');
  assert.equal(await page.locator('.gCraftIngredient').count(),3);
  assert.equal(await page.locator('.gCraftIngredient').last().getAttribute('data-material'),'Cuero bovino curtido');
  await page.screenshot({path:path.join(out,'02-escudo-recetas-y-materiales-dinamicos-1600x900.png'),animations:'disabled',timeout:30000});
  await page.locator('.gCraftMake').click();
  assert.equal(await page.evaluate(()=>window.__CALLS__.at(-1)),'craft:escudo_hierro');
  // Missing stock MUST disable crafting, without mutating the engine or stock.
  await page.evaluate(()=>{window.__CTX__.inventory['Cuero bovino curtido']=0;window.GenesisCraftingModule.render(window.__CTX__,window.__NAV__)});
  assert.equal(await page.locator('.gCraftMake').isDisabled(),true);
  assert.match(await page.locator('.gCraftState').innerText(),/Faltan materiales/);
  await page.evaluate(()=>{window.__CTX__.activeRecipeId='espada_hierro';window.GenesisCraftingModule.render(window.__CTX__,window.__NAV__)});
  assert.equal(await page.locator('.gCraftRecipeDetails h2').innerText(),'Espada de hierro','Follow Ordan quest changes');
  assert.equal(await page.locator('.gCraftRecipe.active').count(),1);
  await page.locator('[data-craft-go="Inventario"]').click();
  assert.equal(await page.evaluate(()=>window.__CALLS__.at(-1)),'tab:Inventario');
  assert.deepEqual(issues,[],'No browser errors / broken local images');
  fs.writeFileSync(path.join(out,'qa.json'),JSON.stringify({passed:true,source:'experimental module + existing approved art',real_gameplay_test:false,viewer3d_loaded:false,recipes:'fixture, rendered dynamically via getRecipeCatalog; no actual game session',issues},null,2));
  console.log('PASS: isolated module, two dynamic recipes, 3 materials, no baked sword, real craft callback contract, quest switch and missing-stock gate');
 } finally {await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1;});
