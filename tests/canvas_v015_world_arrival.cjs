'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const plan=require(path.join(root,'village_plan.js'));
const arrival=require(path.join(root,'v015','canvas-original-arrival-v015.js'));
const manifest=JSON.parse(fs.readFileSync(path.join(root,'v015','manifest.json'),'utf8'));
const source=fs.readFileSync(path.join(root,'genesis_market_v001.js'),'utf8');
const world=fs.readFileSync(path.join(root,'v015','canvas-original-world-v015.js'),'utf8');
const preview=fs.readFileSync(path.join(root,'v015','index.html'),'utf8');
assert.equal(manifest.version,'0.15-v015');
assert.equal(plan.workshops.length,5);
assert.deepEqual(plan.plaza,{x:7,z:16,w:13,d:13});
assert.deepEqual(plan.market,{x:26,z:36,w:12,d:10,reference:true});
const merchant=manifest.characters.find(c=>c.id==='merchant');
const smith=manifest.characters.find(c=>c.id==='artisan');
const ordan=manifest.characters.find(c=>c.id==='ordan');
assert.deepEqual(merchant.position,[25.5,0,36.3],'V014 merchant misplaced');
assert.deepEqual(ordan.position,[1.72,0,1.9],'Ordan original anchor must not move');
assert.deepEqual(smith.position,[7,0,29],'Artisan must begin on original north plaza road');
assert(source.includes('const POS = Object.freeze({x:25.5,y:0,z:36.3})'));
assert(source.includes('const STALL = Object.freeze({x:28.35,y:0,z:37.6})'));
for(const p of plan.workshops)assert(manifest.originalVillage.workshops.some(m=>m.profession===p.profession&&m.position[0]===p.x&&m.position[1]===p.z));
for(const file of ['blacksmith_four_walls_arched_v082.glb','blacksmith_roof_preview.glb','merchant_v02_75962.glb','PG_Dolphin_Fountain_V011_PlayCanvas_HQ_Optimized.glb'])assert(world.includes(file)||manifest.characters.some(c=>c.file.includes(file)),'Missing original asset '+file);
assert(world.includes("['oak',.4,10.7]")&&world.includes("['maple',11.8,11.7]")&&world.includes("['linden',2.2,20.3]")&&world.includes("['ash',11.8,20.3]"),'Four approved plaza tree sites not copied');
assert(preview.includes('GenesisOriginalVillageV015.create(app'));
assert(preview.includes('GenesisVillageArrivalV015.create()'));
assert(preview.includes("if(approach.completed)arrival.arrived()"),'Need original Q1 dialogue after physical arrival');
assert(preview.includes("originalWorld.blocked"),'Original village colliders not bound to manual navigation');
assert(!manifest.originalVillage.futureStoryReorderingApplied,'Do not apply new quests in V015');
const controller=arrival.create();
let st=controller.snapshot();
assert.deepEqual(st.position,[7,0,29]);
assert.equal(st.animation,'Walk_Loop');
let total=0;
for(let i=0;i<2500 && !st.completed;i++){
 const prev=st.position;
 st=controller.step(1/60);
 const distance=Math.hypot(st.position[0]-7,st.position[2]-16);
 // The 4.26m original fountain and .30m avatar collision radius.
 assert(distance>2.43,'Scripted arrival crosses original fountain at '+st.position.join(','));
 total++;
}
assert(st.completed,'Scripted arrival did not reach Ordan');
assert.deepEqual(st.position,[1.72,0,3.5]);
assert.equal(st.animation,'Idle_Loop');
assert(Math.hypot(st.position[0]-1.72,st.position[2]-1.9)<2.1,'Ordan interaction radius missed');
assert(total>500,'Arrival needs to be visibly animated');
assert(st.meters>25,'Arrival should traverse plaza and roads instead of teleporting');
console.log('PASS V015: 5 original workshops, 14 original tree sites, exact market and Ordan, '+st.meters.toFixed(2)+' m Walk_Loop arrival, fountain clearance, Q1 entry.');
